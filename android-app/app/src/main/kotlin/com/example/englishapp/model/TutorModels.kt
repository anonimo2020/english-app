  val better: String,
  val why: String,
  val tip: String? = null,
)

@Serializable
data class PronunciationTip(
  val word: String,
  val phonetic: String,
  val tipEs: String,
)

@Serializable
data class TutorReply(
  val reply: String,
  val translationEs: String? = null,
  val correction: Correction? = null,
  val suggestedReplies: List<String> = emptyList(),
  val pronunciationFocus: List<PronunciationTip> = emptyList(),
  val xpEarned: Int = 12,
  val coachNoteEs: String? = null,
)

@Serializable
data class SessionSummary(
  val strengthsEs: List<String>,
  val focusAreasEs: List<String>,
  val fluencyScore: Int,
  val xpBonus: Int,
)

@Serializable
data class ConversationTurn(
  val id: String,
  val role: String,
  val content: String,
  val translationEs: String? = null,
  val correction: Correction? = null,
  val pronunciationFocus: List<PronunciationTip> = emptyList(),
  val suggestedReplies: List<String> = emptyList(),
  val timestampMs: Long = System.currentTimeMillis(),
  val isSaved: Boolean = false,
  val coachNoteEs: String? = null,
)

@Serializable
data class SavedPhrase(
  val id: String,
  val english: String,
  val spanish: String,
  val note: String = "",
  val source: String = "Tutor",
  val createdAtMs: Long = System.currentTimeMillis(),
)

@Serializable
data class DailyActivity(
  val dateKey: String,
  val dayLabel: String,
  val xp: Int = 0,
  val spokenTurns: Int = 0,
)

@Serializable
data class UserProgress(
  val totalXp: Int = 0,
  val streakDays: Int = 0,
  val lastActiveDate: String = "",
  val sessionsCompleted: Int = 0,
  val totalSpokenTurns: Int = 0,
  val todayXp: Int = 0,
  val dailyGoalXp: Int = 100,
  val weeklyHistory: List<DailyActivity> = emptyList(),
  val completedScenarioIds: Set<String> = emptySet(),
  val completedLessonIds: Set<String> = emptySet(),
  val masteredDrillIds: Set<String> = emptySet(),
  val masteredVocabIds: Set<String> = emptySet(),
)

@Serializable
data class SkillScores(
  val listening: Int,
  val grammar: Int,
  val vocabulary: Int,
  val speaking: Int,
)

@Serializable
data class PlacementResult(
  val estimatedLevel: LearnerLevel,
  val verifiedLevel: LearnerLevel,
  val overallScore: Int,
  val skills: SkillScores,
  val recommendedFocusEs: String,
